#!/usr/bin/env python3
"""
Quark-OS sprite baker.

Reads every PNG in tools/Sprites/, emits two files:
    kernel/desktop/de_sprites.c     - the pixel data + de_image_t structs
    include/quark/de_sprites.h      - extern declarations

Usage:
    python3 tools/png2c.py tools/Sprites kernel/desktop/de_sprites.c \
        include/quark/de_sprites.h

Wallpapers (files starting with "wallpaper_") are downsampled to 1024x768
and stored as opaque RGB. Everything else is stored at its native size with
its original alpha channel.
"""

import sys
import os
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.stderr.write("ERROR: pip install pillow\n")
    sys.exit(1)


WALLPAPER_W = 1024
WALLPAPER_H = 768
ICON_SIZE = 128


def sanitize(name):
    """foo-bar.png -> foo_bar"""
    base = name.rsplit(".", 1)[0]
    return base.replace("-", "_").replace(".", "_").replace(" ", "_")


def load_png(path, is_wallpaper):
    im = Image.open(path)

    if is_wallpaper:
        im = im.convert("RGB")
        if im.size != (WALLPAPER_W, WALLPAPER_H):
            im = im.resize((WALLPAPER_W, WALLPAPER_H), Image.LANCZOS)
        # Add opaque alpha.
        rgba = im.convert("RGBA")
        return rgba, False

    im = im.convert("RGBA")
    alpha_bounds = im.getchannel("A").getbbox()
    if alpha_bounds:
        im = im.crop(alpha_bounds)
    if im.size != (ICON_SIZE, ICON_SIZE):
        im = im.resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS)
    return im, True


def pack_pixels(im):
    """Return list of uint32 in 0xAARRGGBB order."""
    out = []
    px = im.load()
    w, h = im.size
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            out.append((a << 24) | (r << 16) | (g << 8) | b)
    return out


def bake(src_dir, out_c, out_h):
    files = sorted(f for f in os.listdir(src_dir) if f.endswith(".png"))
    if not files:
        sys.stderr.write(f"No PNGs found in {src_dir}\n")
        sys.exit(1)

    images = []
    for fname in files:
        path = os.path.join(src_dir, fname)
        is_wall = fname.startswith("wallpaper_")
        im, _ = load_png(path, is_wall)
        sym = "img_" + sanitize(fname)
        pixels = pack_pixels(im)
        w, h = im.size
        images.append({
            "name": fname,
            "symbol": sym,
            "w": w, "h": h,
            "pixels": pixels,
            "is_wallpaper": is_wall,
        })
        kind = "wallpaper" if is_wall else "icon"
        print(f"  {fname:40s} {w}x{h} {kind}  ->  {sym}  ({len(pixels)*4} bytes)")

    # ---- Emit .c --------------------------------------------------------
    c = []
    c.append("/* AUTO-GENERATED by tools/png2c.py - do not edit. */")
    c.append('#include <quark/de_sprites.h>')
    c.append('#include <quark/de_image.h>')
    c.append("")

    for img in images:
        c.append(f"static const uint32_t {img['symbol']}_pixels[] = {{")
        px = img["pixels"]
        for i in range(0, len(px), 8):
            c.append("    " + ",".join(f"0x{p:08X}" for p in px[i:i+8]) + ",")
        c.append("};")
        c.append("")

    for img in images:
        c.append(f"const de_image_t {img['symbol']} = {{")
        c.append(f"    .w = {img['w']}, .h = {img['h']},")
        c.append(f"    .pixels = {img['symbol']}_pixels,")
        c.append("};")
        c.append("")

    Path(out_c).write_text("\n".join(c))

    # ---- Emit .h --------------------------------------------------------
    h = []
    h.append("/* AUTO-GENERATED by tools/png2c.py - do not edit. */")
    h.append("#ifndef QUARK_DE_SPRITES_H")
    h.append("#define QUARK_DE_SPRITES_H")
    h.append("")
    h.append("#include <quark/de_image.h>")
    h.append("")
    for img in images:
        h.append(f"extern const de_image_t {img['symbol']};")
    h.append("")
    h.append("#endif")
    Path(out_h).write_text("\n".join(h))

    print(f"\nWrote {out_c}")
    print(f"Wrote {out_h}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.stderr.write(__doc__)
        sys.exit(1)
    bake(sys.argv[1], sys.argv[2], sys.argv[3])