#!/usr/bin/env python3
"""
Quark-OS font baker.

Usage:
    python3 gen_font.py <font.ttf> <out.c> <symbol_prefix> <size_pt> <char_start> <char_end>

Example:
    python3 gen_font.py tools/fonts/static/Inter_18pt-Regular.ttf \
        kernel/desktop/de_font_data_body.c de_font_body 9 32 126
"""

import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.stderr.write("ERROR: pip install pillow\n")
    sys.exit(1)


def bake(font_path, out_path, prefix, size_pt, cstart, cend):
    font = ImageFont.truetype(font_path, size_pt)

    ascent, descent = font.getmetrics()
    line_h = ascent + descent

    glyphs = []
    for code in range(cstart, cend + 1):
        ch = chr(code)

        # Generous canvas so descenders and overhangs have room.
        canvas_size = size_pt * 6
        img = Image.new("L", (canvas_size, canvas_size), 0)
        d = ImageDraw.Draw(img)
        ox, oy = canvas_size // 3, canvas_size // 3
        d.text((ox, oy), ch, fill=255, font=font)

        bbox = img.getbbox()
        if bbox is None:
            # Empty glyph (space, etc.) -- keep its advance.
            adv = int(round(font.getlength(ch)))
            glyphs.append({
                "code": code, "advance": adv,
                "w": 0, "h": 0, "bx": 0, "by": 0,
                "bitmap": [],
            })
            continue

        l, t, r, b = bbox
        w = r - l
        h = b - t

        bitmap = []
        for yy in range(t, b):
            row = [img.getpixel((xx, yy)) for xx in range(l, r)]
            bitmap.append(row)

        adv = int(round(font.getlength(ch)))
        bx = l - ox
        by = t - oy    # negative => above the baseline

        glyphs.append({
            "code": code, "advance": adv,
            "w": w, "h": h, "bx": bx, "by": by,
            "bitmap": bitmap,
        })

    # Kerning: joint-width heuristic. Good enough for AA UI text.
    kern_pairs = []
    for a in range(cstart, cend + 1):
        for b in range(cstart, cend + 1):
            pa, pb = chr(a), chr(b)
            k = int(round(font.getlength(pa + pb)
                          - font.getlength(pa)
                          - font.getlength(pb)))
            if k != 0:
                kern_pairs.append((a, b, k))

    # Flatten the atlas and record per-glyph offsets.
    atlas = []
    offsets = []
    for g in glyphs:
        offsets.append(len(atlas))
        for row in g["bitmap"]:
            atlas.extend(row)

    out = []
    out.append("/* AUTO-GENERATED by tools/gen_font.py - do not edit. */")
    out.append('#include <quark/de_font.h>')
    out.append("")

    out.append(f"static const uint8_t {prefix}_atlas[] = {{")
    for i in range(0, len(atlas), 16):
        out.append("    " + ",".join(f"0x{b:02X}" for b in atlas[i:i+16]) + ",")
    out.append("};")
    out.append("")

    out.append(f"static const de_glyph_t {prefix}_glyphs[] = {{")
    for i, g in enumerate(glyphs):
        out.append(
            f"    {{ {g['code']}, {g['advance']}, {g['w']}, {g['h']}, "
            f"{g['bx']}, {g['by']}, {offsets[i]} }},"
        )
    out.append("};")
    out.append("")

    out.append(f"static const de_kern_t {prefix}_kerns[] = {{")
    for a, b, k in kern_pairs:
        out.append(f"    {{ {a}, {b}, {k} }},")
    out.append("};")
    out.append("")

    out.append(f"const de_font_t {prefix} = {{")
    out.append(f"    {ascent}, {descent}, {line_h},")
    out.append(f"    {prefix}_glyphs, {len(glyphs)},")
    out.append(f"    {cstart}, {cend},")
    out.append(f"    {prefix}_atlas, {len(atlas)},")
    out.append(f"    {prefix}_kerns, {len(kern_pairs)},")
    out.append("};")

    Path(out_path).write_text("\n".join(out))
    print(f"Wrote {out_path}: {len(atlas)} B atlas, "
          f"{len(glyphs)} glyphs, {len(kern_pairs)} kern pairs, "
          f"ascent={ascent} descent={descent}")


if __name__ == "__main__":
    if len(sys.argv) != 7:
        sys.stderr.write(__doc__)
        sys.exit(1)
    bake(sys.argv[1], sys.argv[2], sys.argv[3],
         int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6]))