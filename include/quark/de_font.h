#ifndef QUARK_DE_FONT_H
#define QUARK_DE_FONT_H

#include <quark/kernel.h>

typedef struct {
    uint16_t code;      /* Unicode codepoint */
    uint8_t  advance;   /* pen movement after drawing */
    uint8_t  w, h;      /* bitmap dimensions */
    int8_t   bx, by;    /* bearing: offset from pen origin to bitmap top-left */
    uint32_t offset;    /* offset into atlas */
} de_glyph_t;

typedef struct {
    uint16_t left;      /* left codepoint */
    uint16_t right;     /* right codepoint */
    int8_t   delta;     /* kerning adjustment to advance */
} de_kern_t;

typedef struct {
    uint8_t  ascent;
    uint8_t  descent;
    uint8_t  line_h;
    const de_glyph_t* glyphs;
    uint32_t glyph_count;
    uint32_t cstart;
    uint32_t cend;
    const uint8_t* atlas;
    uint32_t atlas_len;
    const de_kern_t* kerns;
    uint32_t kern_count;
} de_font_t;

/* Baked fonts. The _body and _title variants are generated by gen_font.py. */
extern const de_font_t de_font_body;   /* ~9pt, for regular UI text */
extern const de_font_t de_font_title;  /* ~13pt, for window titles */

// Cursor metrics and drawing functions
/* Draw a blinking text caret at (x, baseline_y) using the current tick. */
void de_font_draw_caret(const de_font_t* f, int x, int baseline_y,
                        uint32_t color);

/* Metrics */
int de_font_text_width (const de_font_t* f, const char* s);
int de_font_text_width_n(const de_font_t* f, const char* s, int max_chars);

/* Drawing */
void de_font_draw_char (const de_font_t* f, int x, int y, char c,
                        uint32_t color, uint8_t alpha);
void de_font_draw_text (const de_font_t* f, int x, int y, const char* s,
                        uint32_t color, uint8_t alpha);

#endif